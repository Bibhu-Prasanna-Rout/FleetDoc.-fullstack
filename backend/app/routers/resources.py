@router.post("/{collection}")
def create_collection(
    collection: str,
    payload: dict,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if collection not in MODEL_MAP:
        raise HTTPException(404, "Resource not found")

    if not allowed(user, collection, "add", db):
        raise HTTPException(403, "Permission denied")

    Model = MODEL_MAP[collection]

    # --------------------------------------------------------
    # SPECIAL LOAN HANDLING
    # --------------------------------------------------------
    if collection == "loans":
        normalized = _normalize_loan_payload(payload)

        if not normalized["vehicle"]:
            raise HTTPException(
                422,
                "Vehicle is required for a loan",
            )

        if normalized["principal"] <= 0:
            raise HTTPException(
                422,
                "Loan amount must be greater than 0",
            )

        if normalized["monthly_amount"] <= 0:
            raise HTTPException(
                422,
                "Monthly EMI amount could not be determined",
            )

        if not normalized["emi_start_date"]:
            raise HTTPException(
                422,
                "EMI start date is required",
            )

        if normalized["duration_type"] == "dateRange":
            if not normalized["emi_closing_date"]:
                raise HTTPException(
                    422,
                    "EMI closing date is required for date range mode",
                )

            if normalized["emi_start_date"] > normalized["emi_closing_date"]:
                raise HTTPException(
                    422,
                    "EMI closing date must be on or after the start date",
                )

            normalized["tenure_months"] = _months_inclusive(
                normalized["emi_start_date"],
                normalized["emi_closing_date"],
            )

        else:
            if normalized["tenure_months"] <= 0:
                raise HTTPException(
                    422,
                    "Loan duration must be greater than 0 months",
                )

            # Make sure the closing date exists for fixed-month loans.
            if not normalized["closing_date"]:
                normalized["closing_date"] = _add_months(
                    normalized["emi_start_date"],
                    normalized["tenure_months"] - 1,
                ).isoformat()

        loan_data = dict(normalized["data"])

        # Keep these values available to the frontend exactly as it
        # already uses them.
        loan_data["durationType"] = normalized["duration_type"]
        loan_data["loanAmount"] = normalized["principal"]
        loan_data["monthlyAmount"] = normalized["monthly_amount"]
        loan_data["interestRate"] = normalized["interest_rate"]
        loan_data["loanDuration"] = (
            normalized["tenure_months"]
            if normalized["duration_type"] == "months"
            else "dateRange"
        )

        if normalized["loan_number"] is not None:
            loan_data["loanNumber"] = normalized["loan_number"]

        if normalized["emi_start_date"]:
            loan_data["emiStartDate"] = normalized["emi_start_date"].isoformat()

        if normalized["emi_closing_date"]:
            loan_data["emiClosingDate"] = normalized["emi_closing_date"].isoformat()

        # financerBank is the field used by the current frontend.
        if normalized["bank"]:
            loan_data["financerBank"] = normalized["bank"]

        obj = Loan(
            vehicle=normalized["vehicle"],
            bank=normalized["bank"],
            principal=normalized["principal"],
            monthly_amount=normalized["monthly_amount"],
            interest_rate=normalized["interest_rate"],
            tenure_months=normalized["tenure_months"],
            start_date=normalized["start_date"],
            closing_date=normalized["closing_date"],
            status=normalized["status"],
            data=loan_data,
        )

        db.add(obj)

        try:
            db.flush()

            # Generate all EMI records before committing the loan.
            created_emis = _generate_emis_for_loan(db, obj)

            if not created_emis:
                raise HTTPException(
                    422,
                    "No EMI records could be generated from the selected loan dates and duration",
                )

            # The schedule has now been deliberately created for this loan.
            # Keep this flag so deleting EMI records later is respected and
            # the legacy compatibility sync does not recreate them.
            _mark_emi_schedule_initialized(obj)

            db.commit()
            db.refresh(obj)

        except HTTPException:
            db.rollback()
            raise

        except IntegrityError:
            db.rollback()
            raise HTTPException(
                409,
                "Duplicate or invalid loan record",
            )

        except Exception:
            db.rollback()
            raise

        db.add(
            AuditLog(
                user_id=user.id,
                action="create",
                entity=Loan.__tablename__,
                entity_id=str(obj.id),
                details={
                    "emiCount": len(created_emis),
                    "durationType": normalized["duration_type"],
                },
            )
        )

        db.commit()

        return SERIAL[collection](obj)

    # --------------------------------------------------------
    # NORMAL RESOURCES
    # --------------------------------------------------------

    obj = Model(**clean_payload(payload, Model))

    db.add(obj)

    try:
        db.commit()
        db.refresh(obj)

    except IntegrityError:
        db.rollback()
        raise HTTPException(
            409,
            "Duplicate or invalid record",
        )

    db.add(
        AuditLog(
            user_id=user.id,
            action="create",
            entity=Model.__tablename__,
            entity_id=str(obj.id),
            details={},
        )
    )

    db.commit()

    return SERIAL[collection](obj)


