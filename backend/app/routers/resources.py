@router.delete("/{collection}/{item_id}")
def delete_collection(
    collection: str,
    item_id: int,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if collection not in MODEL_MAP:
        raise HTTPException(404, "Resource not found")

    if not allowed(user, collection, "delete", db):
        raise HTTPException(403, "Permission denied")

    Model = MODEL_MAP[collection]
    obj = db.get(Model, item_id)

    if not obj:
        raise HTTPException(404, "Record not found")

    deleted_emi_count = 0

    try:
        # ----------------------------------------------------
        # LOAN DELETE
        # ----------------------------------------------------
        # A loan can have multiple EMI records.
        # The database relationship currently uses
        # ON DELETE SET NULL, so deleting the loan alone
        # does NOT delete its EMI records.
        #
        # Therefore, delete all EMIs belonging to this loan
        # before deleting the loan itself.
        # ----------------------------------------------------

        if collection == "loans":
            deleted_emi_count = (
                db.query(EMI)
                .filter(EMI.loan_id == obj.id)
                .delete(
                    synchronize_session=False
                )
            )

        # ----------------------------------------------------
        # DELETE MAIN RECORD
        # ----------------------------------------------------

        deleted_id = obj.id

        db.delete(obj)

        # Flush before creating the audit record.
        db.flush()

        # ----------------------------------------------------
        # AUDIT LOG
        # ----------------------------------------------------

        db.add(
            AuditLog(
                user_id=user.id,
                action="delete",
                entity=Model.__tablename__,
                entity_id=str(deleted_id),
                details={
                    "collection": collection,
                    "deletedEmis": deleted_emi_count,
                },
            )
        )

        db.commit()

        return {
            "message": "Record deleted successfully",
            "id": deleted_id,
            "collection": collection,
            "deletedEmis": deleted_emi_count,
        }

    except IntegrityError:
        db.rollback()

        raise HTTPException(
            status_code=409,
            detail=(
                "This record cannot be deleted because it is "
                "still referenced by other data."
            ),
        )

    except Exception:
        db.rollback()
        raise

