def allowed(user, collection, action, db=None):
    if user.role == "Admin":
        return True

    perms = user.permissions or {}
    module = ACTION_MODULE[collection]

    if isinstance(perms.get(module), dict) and perms[module].get(action):
        return True

    if isinstance(perms.get(collection), dict) and perms[collection].get(action):
        return True

    role_block = perms.get(user.role)
    if isinstance(role_block, dict) and role_block.get(action):
        return True

    if db is not None:
        s = db.query(Setting).filter(Setting.key == "global").first()
        rp = (s.value or {}).get("rolePermissions", {}) if s else {}
        role_block = rp.get(user.role, {})

        if isinstance(role_block, dict) and role_block.get(action):
            return True

    return False


