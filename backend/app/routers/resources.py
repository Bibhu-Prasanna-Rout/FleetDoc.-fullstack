@router.get("/{collection}")
def list_collection(
    collection: str,
    q: str | None = None,
    page: int = 1,
    limit: int = 100,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if collection not in MODEL_MAP:
        raise HTTPException(404, "Resource not found")

    # Important:
    # Repair loans created by the previous backend version.
    # This means existing loans can start showing EMI records
    # without the user having to recreate them.
    if collection == "emis":
        _sync_missing_loan_emis(db)

    Model = MODEL_MAP[collection]
    query = db.query(Model)

    if q:
        fields = [
            c
            for c in (
                "number",
                "vehicle",
                "type",
                "status",
                "owner",
                "bank",
                "email",
            )
            if hasattr(Model, c)
        ]

        if fields:
            from sqlalchemy import or_

            query = query.filter(
                or_(
                    *[
                        getattr(Model, field).ilike(f"%{q}%")
                        for field in fields
                    ]
                )
            )

    rows = (
        query.order_by(Model.id.desc())
        .offset((page - 1) * limit)
        .limit(min(limit, 500))
        .all()
    )

    return [SERIAL[collection](x) for x in rows]


