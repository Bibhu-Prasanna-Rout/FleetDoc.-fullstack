@router.patch("/{collection}/{item_id}")
def update_collection(
    collection: str,
    item_id: int,
    payload: dict,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if collection not in MODEL_MAP:
        raise HTTPException(404, "Resource not found")

    if not allowed(user, collection, "edit", db):
        raise HTTPException(403, "Permission denied")

    Model = MODEL_MAP[collection]
    obj = db.get(Model, item_id)

    if not obj:
        raise HTTPException(404, "Record not found")

    # --------------------------------------------------------
    # SPECIAL LOAN UPDATE
    # --------------------------------------------------------
    if collection == "loans":
        # Rebuild the complete loan payload from the existing
        # database record + incoming frontend fields.
        current = {
            "vehicle": obj.vehicle,
            "bank": obj.bank,
            "principal": obj.principal,
            "monthlyAmount": obj.monthly_amount,
            "interestRate": obj.interest_rate,
            "tenureMonths": obj.tenure_months,
            "startDate": obj.start_date,
            "closingDate": obj.closing_date,
            "status": obj.status,
            **(obj.data or {}),
        }

        current.update(payload or {})

        normalized = _normalize_loan_payload(current)

        if not normalized["vehicle"]:
            raise HTTPException(422, "Vehicle is required for a loan")

        if normalized["principal"] <= 0:
            raise HTTPException(422, "Loan amount must be greater than 0")

        if normalized["monthly_amount"] <= 0:
            raise HTTPException(
                422,
                "Monthly EMI amount could not be determined",
            )

        if not normalized["emi_start_date"]:
            raise HTTPException(
                422,
                "EMI start date is required",
            )

        if normalized["duration_type"] == "dateRange":
            if not normalized["emi_closing_date"]:
                raise HTTPException(
                    422,
                    "EMI closing date is required for date range mode",
                )

            if normalized["emi_start_date"] > normalized["emi_closing_date"]:
                raise HTTPException(
                    422,
                    "EMI closing date must be on or after the start date",
                )

            normalized["tenure_months"] = _months_inclusive(
                normalized["emi_start_date"],
                normalized["emi_closing_date"],
            )

        else:
            if normalized["tenure_months"] <= 0:
                raise HTTPException(
                    422,
                    "Loan duration must be greater than 0 months",
                )

            normalized["closing_date"] = _add_months(
                normalized["emi_start_date"],
                normalized["tenure_months"] - 1,
            ).isoformat()

        # Delete the previous EMI schedule because the loan schedule
        # has changed.
        db.query(EMI).filter(EMI.loan_id == obj.id).delete(
            synchronize_session=False
        )

        obj.vehicle = normalized["vehicle"]
        obj.bank = normalized["bank"]
        obj.principal = normalized["principal"]
        obj.monthly_amount = normalized["monthly_amount"]
        obj.interest_rate = normalized["interest_rate"]
        obj.tenure_months = normalized["tenure_months"]
        obj.start_date = normalized["start_date"]
        obj.closing_date = normalized["closing_date"]
        obj.status = normalized["status"]

        loan_data = dict(normalized["data"])
        loan_data["durationType"] = normalized["duration_type"]
        loan_data["loanAmount"] = normalized["principal"]
        loan_data["monthlyAmount"] = normalized["monthly_amount"]
        loan_data["interestRate"] = normalized["interest_rate"]
        loan_data["loanDuration"] = (
            normalized["tenure_months"]
            if normalized["duration_type"] == "months"
            else "dateRange"
        )

        if normalized["loan_number"] is not None:
            loan_data["loanNumber"] = normalized["loan_number"]

        if normalized["emi_start_date"]:
            loan_data["emiStartDate"] = normalized["emi_start_date"].isoformat()

        if normalized["emi_closing_date"]:
            loan_data["emiClosingDate"] = normalized["emi_closing_date"].isoformat()

        if normalized["bank"]:
            loan_data["financerBank"] = normalized["bank"]

        obj.data = loan_data

        db.flush()

        created_emis = _generate_emis_for_loan(db, obj)

        if not created_emis:
            db.rollback()
            raise HTTPException(
                422,
                "No EMI records could be generated from the updated loan",
            )

        # The updated loan now has a fresh, authoritative EMI schedule.
        _mark_emi_schedule_initialized(obj)

        db.commit()
        db.refresh(obj)

        return SERIAL[collection](obj)

    # --------------------------------------------------------
    # NORMAL UPDATE
    # --------------------------------------------------------

    for key, value in clean_payload(payload, Model).items():
        setattr(obj, key, value)

    db.commit()
    db.refresh(obj)

    return SERIAL[collection](obj)


