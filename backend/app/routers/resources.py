def _audit_module(entity: str | None, details: dict | None = None) -> str:
    """Convert database entity names into the labels used by the UI."""
    value = str(entity or "").strip()
    mapping = {
        "vehicles": "Vehicles",
        "documents": "Documents",
        "emis": "EMI",
        "loans": "EMI",
        "challans": "Challans",
        "road_taxes": "Road Tax",
        "users": "Users",
        "Settings": "Settings",
        "Authentication": "Authentication",
        "notifications": "Notifications",
        "subscriptions": "Premium",
        "payments": "Payments",
    }
    if value in mapping:
        return mapping[value]
    if value:
        return value.replace("_", " ").title()
    return "System"


def _audit_action(action: str | None) -> str:
    mapping = {
        "create": "Created",
        "update": "Updated",
        "delete": "Deleted",
        "settings_updated": "Settings Updated",
        "login": "Signed In",
        "login_2fa_requested": "2FA Code Requested",
        "login_2fa_verified": "2FA Verified",
        "password_change": "Password Changed",
        "password_reset": "Password Reset",
    }
    value = str(action or "").strip()
    return mapping.get(value, value.replace("_", " ").title() or "Activity")


def _audit_out(row, user=None):
    """Return both canonical API fields and the legacy UI field names."""
    created = row.created_at.isoformat() if row.created_at else None
    resolved_user = user
    if resolved_user is None and getattr(row, "user", None):
        resolved_user = row.user

    user_name = resolved_user.name if resolved_user else None
    user_email = resolved_user.email if resolved_user else None
    module = _audit_module(row.entity, row.details or {})
    action = _audit_action(row.action)

    return {
        "id": row.id,
        "userId": row.user_id,
        "userName": user_name,
        "userEmail": user_email,
        "user": user_name,
        "action": action,
        "actionKey": row.action,
        "entity": row.entity,
        "entityId": row.entity_id,
        "module": module,
        "description": (row.details or {}).get("description", ""),
        "details": row.details or {},
        "createdAt": created,
        "timestamp": created,
        "time": created,
    }


@router.get("/audit-logs")
def get_audit_logs(
    limit: int = Query(500, ge=1, le=2000),
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if user.role != "Admin" and not (user.permissions or {}).get("settings", {}).get("view"):
        raise HTTPException(403, "Audit log permission denied")

    rows = (
        db.query(AuditLog)
        .order_by(AuditLog.created_at.desc(), AuditLog.id.desc())
        .limit(limit)
        .all()
    )
    # Avoid requiring a relationship on AuditLog; resolve users once.
    user_ids = {r.user_id for r in rows if r.user_id is not None}
    users_by_id = {}
    if user_ids:
        from app.models.models import User
        users_by_id = {u.id: u for u in db.query(User).filter(User.id.in_(user_ids)).all()}
    return [_audit_out(row, users_by_id.get(row.user_id)) for row in rows]


@router.delete("/audit-logs")
def delete_audit_logs(
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if user.role != "Admin":
        raise HTTPException(403, "Only Admin can clear audit logs")

    count = db.query(AuditLog).delete(synchronize_session=False)
    # Record the clear action cannot be kept in the same table after deletion,
    # so it is intentionally not re-added.
    db.commit()
    return {"message": "Audit logs cleared successfully", "deleted": count}


