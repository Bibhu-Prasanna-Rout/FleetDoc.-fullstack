@router.put("/settings/global")
def update_settings(
    payload: dict,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):
    if user.role != "Admin" and not (
        user.permissions or {}
    ).get("settings", {}).get("edit"):
        raise HTTPException(
            403,
            "Settings permission denied",
        )

    s = (
        db.query(Setting)
        .filter(Setting.key == "global")
        .first()
    )

    if not s:
        s = Setting(
            key="global",
            value={},
        )
        db.add(s)

    s.value = payload
    db.add(
        AuditLog(
            user_id=user.id,
            action="settings_updated",
            entity="Settings",
            entity_id=str(s.id),
            details={
                "security": {
                    "two_factor": bool(payload.get("twoFactorAuthentication", payload.get("twoFactor", False))),
                    "strong_password": bool(payload.get("strongPasswordRequired", payload.get("strongPassword", True))),
                    "session_timeout": payload.get("sessionTimeout"),
                },
            },
        )
    )
    db.commit()

    return s.value



