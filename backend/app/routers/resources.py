def _to_float(value, default=0.0):
    if value is None or value == "":
        return default

    if isinstance(value, bool):
        return float(value)

    try:
        if isinstance(value, str):
            value = value.replace(",", "").replace("₹", "").strip()

        return float(value)
    except (TypeError, ValueError):
        return default


def _to_int(value, default=0):
    if value is None or value == "":
        return default

    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return default


def _parse_date(value):
    """
    Accept the date formats commonly used by FleetDoc.

    Examples:
        2026-07-10
        10-07-2026
        10/07/2026
        10.07.2026
        10 Jul 2026
        10 July 2026
    """

    if value is None:
        return None

    if isinstance(value, datetime):
        return value.date()

    if isinstance(value, date):
        return value

    text = str(value).strip()

    if not text:
        return None

    # ISO datetime, e.g. 2026-07-10T00:00:00
    if "T" in text:
        text = text.split("T", 1)[0]

    formats = (
        "%Y-%m-%d",
        "%d-%m-%Y",
        "%d/%m/%Y",
        "%d.%m.%Y",
        "%d %b %Y",
        "%d %B %Y",
        "%Y/%m/%d",
    )

    for fmt in formats:
        try:
            return datetime.strptime(text, fmt).date()
        except ValueError:
            continue

    return None


def _date_to_iso(value):
    parsed = _parse_date(value)

    if parsed is None:
        return None

    return parsed.isoformat()


def _add_months(source_date, months=1):
    """
    Add calendar months while preserving the day whenever possible.

    Example:
        10 Jul 2026 + 1 month = 10 Aug 2026
    """

    month_index = source_date.month - 1 + months
    year = source_date.year + month_index // 12
    month = month_index % 12 + 1

    day = min(
        source_date.day,
        calendar.monthrange(year, month)[1],
    )

    return date(year, month, day)


def _months_inclusive(start_date, end_date):
    """
    Count calendar EMI dates inclusively.

    10 Jul 2026 -> 10 Dec 2026 = 6
    """

    if start_date > end_date:
        return 0

    return (
        (end_date.year - start_date.year) * 12
        + (end_date.month - start_date.month)
        + 1
    )


