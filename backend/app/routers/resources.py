# LOAN PAYLOAD NORMALIZATION
# ============================================================

def _normalize_loan_payload(payload):
    """
    Convert the FleetDoc frontend loan fields into the canonical
    Loan database fields.

    Frontend fields supported:

        vehicle
        financerBank / bank
        loanAmount / amount / principal
        monthlyAmount
        interestRate
        durationType
        loanDuration
        tenureMonths
        emiStartDate / startDate
        emiClosingDate / closingDate
        loanNumber

    The original frontend fields are also preserved in `data`.
    """

    source = dict(payload or {})
    data = dict(source.get("data") or {})

    # Preserve all original frontend fields inside data.
    for key, value in source.items():
        if key != "data":
            data[key] = value

    vehicle = (
        source.get("vehicle")
        or source.get("vehicleNo")
        or source.get("vehicleNumber")
        or ""
    )

    bank = (
        source.get("bank")
        or source.get("financerBank")
        or source.get("bankName")
    )

    principal = _to_float(
        source.get(
            "principal",
            source.get(
                "loanAmount",
                source.get("amount", 0),
            ),
        )
    )

    monthly_amount = _to_float(
        source.get(
            "monthlyAmount",
            source.get("monthly_amount", 0),
        )
    )

    interest_rate = _to_float(
        source.get(
            "interestRate",
            source.get("interest_rate", 0),
        )
    )

    duration_type = str(
        source.get(
            "durationType",
            source.get("duration_type", "months"),
        )
        or "months"
    ).strip().lower()

    # Accept several frontend spellings.
    if duration_type in {
        "daterange",
        "date-range",
        "date_range",
        "range",
    }:
        duration_type = "dateRange"
    else:
        duration_type = "months"

    raw_duration = source.get(
        "loanDuration",
        source.get("tenureMonths", source.get("tenure_months", 0)),
    )

    # If an old frontend accidentally sends loanDuration="dateRange",
    # do not use that as the numeric tenure.
    if isinstance(raw_duration, str) and raw_duration.strip().lower() in {
        "daterange",
        "date-range",
        "date_range",
        "range",
    }:
        raw_duration = 0

    tenure_months = _to_int(raw_duration)

    start_value = source.get(
        "emiStartDate",
        source.get(
            "startDate",
            source.get("start_date"),
        ),
    )

    closing_value = source.get(
        "emiClosingDate",
        source.get(
            "closingDate",
            source.get("closing_date"),
        ),
    )

    start_date = _parse_date(start_value)
    closing_date = _parse_date(closing_value)

    # Date-range mode determines the number of EMI records from the
    # selected start/end dates.
    if duration_type == "dateRange":
        if start_date and closing_date:
            tenure_months = _months_inclusive(
                start_date,
                closing_date,
            )
        else:
            tenure_months = 0

    # For fixed-month mode, closing date is calculated from the
    # start date and number of months when possible.
    elif start_date and tenure_months > 0:
        closing_date = _add_months(start_date, tenure_months - 1)

    # If monthly EMI was not supplied, calculate it.
    #
    # With interest:
    #     standard reducing-balance EMI formula
    #
    # Without interest:
    #     principal / number of EMI records
    if monthly_amount <= 0 and principal > 0 and tenure_months > 0:
        if interest_rate > 0:
            monthly_rate = interest_rate / 12 / 100
            factor = (1 + monthly_rate) ** tenure_months

            if factor != 1:
                monthly_amount = (
                    principal
                    * monthly_rate
                    * factor
                    / (factor - 1)
                )
        else:
            monthly_amount = principal / tenure_months

    loan_number = (
        source.get("loanNumber")
        or source.get("loan_number")
    )

    return {
        "vehicle": str(vehicle).strip(),
        "bank": str(bank).strip() if bank is not None else None,
        "principal": principal,
        "monthly_amount": monthly_amount,
        "interest_rate": interest_rate,
        "tenure_months": tenure_months,
        "start_date": start_date.isoformat() if start_date else None,
        "closing_date": closing_date.isoformat() if closing_date else None,
        "status": str(source.get("status") or "Active"),
        "data": data,
        "duration_type": duration_type,
        "loan_number": loan_number,
        "emi_start_date": start_date,
        "emi_closing_date": closing_date,
    }


# ============================================================
# EMI GENERATION
# ============================================================

def _build_emi_rows(loan):
    """
    Generate EMI rows for one loan.

    Mode 1:
        durationType = months
        loanDuration = 60
        -> exactly 60 EMI records

    Mode 2:
        durationType = dateRange
        start = 10-07-2026
        end   = 10-12-2026
        -> exactly 6 EMI records

    Both start and end dates are included.
    """

    data = dict(loan.data or {})

    duration_type = str(
        data.get("durationType", "months") or "months"
    ).strip().lower()

    if duration_type in {
        "daterange",
        "date-range",
        "date_range",
        "range",
    }:
        duration_type = "dateRange"
    else:
        duration_type = "months"

    start_date = _parse_date(
        data.get("emiStartDate")
        or loan.start_date
        or data.get("startDate")
    )

    end_date = _parse_date(
        data.get("emiClosingDate")
        or loan.closing_date
        or data.get("closingDate")
    )

    # Recover frontend loanAmount/monthlyAmount if an older record
    # was saved before normalization.
    principal = _to_float(
        loan.principal
        if loan.principal
        else data.get(
            "loanAmount",
            data.get("amount", 0),
        )
    )

    monthly_amount = _to_float(
        loan.monthly_amount
        if loan.monthly_amount
        else data.get("monthlyAmount", 0)
    )

    interest_rate = _to_float(
        loan.interest_rate
        if loan.interest_rate
        else data.get("interestRate", 0)
    )

    tenure_months = _to_int(
        loan.tenure_months
        if loan.tenure_months
        else data.get("loanDuration", 0)
    )

    if duration_type == "dateRange":
        if not start_date or not end_date:
            return []

        if start_date > end_date:
            return []

        tenure_months = _months_inclusive(
            start_date,
            end_date,
        )

    else:
        if tenure_months <= 0:
            return []

        if not start_date:
            return []

        # Fixed tenure mode always creates exactly N EMI dates.
        end_date = _add_months(
            start_date,
            tenure_months - 1,
        )

    if monthly_amount <= 0 and principal > 0:
        if interest_rate > 0:
            monthly_rate = interest_rate / 12 / 100
            factor = (1 + monthly_rate) ** tenure_months

            if factor != 1:
                monthly_amount = (
                    principal
                    * monthly_rate
                    * factor
                    / (factor - 1)
                )
        else:
            monthly_amount = principal / tenure_months

    if monthly_amount <= 0:
        return []

    rows = []

    current_date = start_date
    generated = 0

    while generated < tenure_months:
        if current_date > end_date:
            break

        rows.append(
            {
                "loan_id": loan.id,
                "vehicle": loan.vehicle,
                "bank": loan.bank,
                "due": current_date.isoformat(),
                "amount": round(monthly_amount, 2),
                "status": "Pending",
                "paid_date": None,
                "data": {
                    "loanId": loan.id,
                    "durationType": duration_type,
                    "emiNumber": generated + 1,
                    "totalEmis": tenure_months,
                    "principal": principal,
                    "monthlyAmount": round(monthly_amount, 2),
                    "interestRate": interest_rate,
                },
            }
        )

        generated += 1
        current_date = _add_months(
            start_date,
            generated,
        )

    return rows


def _generate_emis_for_loan(db, loan):
    """
    Create the EMI schedule for a loan only when the loan does not
    already have EMI records.

    The loan's JSON data also stores ``emiScheduleInitialized``.
    That flag is important because an intentionally deleted EMI
    schedule must NOT be recreated by the compatibility sync.
    """

    existing = (
        db.query(EMI)
        .filter(EMI.loan_id == loan.id)
        .count()
    )

    if existing > 0:
        return []

    rows = _build_emi_rows(loan)

    if not rows:
        return []

    created = []

    for row in rows:
        emi = EMI(**row)
        db.add(emi)
        created.append(emi)

    return created


def _mark_emi_schedule_initialized(loan):
    """Mark a loan as having an intentionally initialized EMI schedule."""
    data = dict(loan.data or {})
    data["emiScheduleInitialized"] = True
    loan.data = data


def _sync_missing_loan_emis(db):
    """
    Repair legacy loans that pre-date automatic EMI generation.

    IMPORTANT: this must only run for loans whose EMI schedule has
    never been initialized. Once a schedule has been created, the
    ``emiScheduleInitialized`` flag remains true even if the user
    intentionally deletes some or all EMI records. This prevents the
    deleted EMI records from coming back on the next GET /emis.
    """

    loans = db.query(Loan).order_by(Loan.id.asc()).all()
    changed = False

    for loan in loans:
        data = dict(loan.data or {})

        # Already initialized means the current EMI state is authoritative.
        # Never regenerate records merely because the user deleted them.
        if data.get("emiScheduleInitialized") is True:
            continue

        existing = (
            db.query(EMI)
            .filter(EMI.loan_id == loan.id)
            .count()
        )

        if existing > 0:
            # Legacy loan already has a schedule. Remember that fact so
            # future intentional deletions are not repaired automatically.
            _mark_emi_schedule_initialized(loan)
            changed = True
            continue

        created = _generate_emis_for_loan(db, loan)

        if created:
            _mark_emi_schedule_initialized(loan)
            changed = True

    if changed:
        db.commit()


