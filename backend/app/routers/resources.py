def clean_payload(payload, model):
    payload = dict(payload or {})

    aliases = {
        "contactNo": "phone",
        "challanNo": "challan_no",
        "taxType": "tax_type",
        "fileName": "file_name",
        "fileUrl": "file_url",
        "loanId": "loan_id",
        "paidDate": "paid_date",
        "monthlyAmount": "monthly_amount",
        "interestRate": "interest_rate",
        "tenureMonths": "tenure_months",
        "startDate": "start_date",
        "closingDate": "closing_date",
    }

    for alias, column in aliases.items():
        if alias in payload and column not in payload:
            payload[column] = payload.pop(alias)

    known = set(model.__table__.columns.keys())

    extra = {
        key: value
        for key, value in payload.items()
        if key not in known
    }

    data = dict(payload.get("data") or {})
    data.update(extra)

    # Primary keys are generated by the database.
    # The frontend may send an ``id`` (often a JavaScript timestamp),
    # but PostgreSQL stores these IDs as INTEGER. A millisecond timestamp
    # such as 1790597243881 is far outside the INTEGER range and causes:
    #   psycopg2.errors.NumericValueOutOfRange: integer out of range
    #
    # Therefore, never accept a client-supplied id during CREATE.
    # SQLAlchemy/PostgreSQL will generate the next valid integer ID.
    payload = {
        key: value
        for key, value in payload.items()
        if key in known and key not in {"data", "id"}
    }

    if "data" in known:
        payload["data"] = data

    return payload


